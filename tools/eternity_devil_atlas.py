#!/usr/bin/env python3
"""Eternity Devil v4: the build data for the cuboid renderer, nothing typed by hand.

Runs the concept's own export (tools/eternity_devil_concept.py export), then

  * copies its atlas (eternity_devil.png, 704 x 512) to the mod's entity textures, and
  * writes client/EternityDevilLayout.java: the boxes, eyes, teeth, heart, small mouths and sinews of the
    layout as constants, in the frame described in the file's own comment.

    python tools/eternity_devil_atlas.py
"""
import json
import os
import shutil
import subprocess
import sys
import tempfile

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
TEXTURE = os.path.join(ROOT, "chainsawman", "src", "main", "resources", "assets", "chainsawman", "textures", "entity", "eternity_devil.png")
JAVA = os.path.join(ROOT, "chainsawman", "src", "client", "java", "io", "github", "kortev", "chainsawman", "client", "EternityDevilLayout.java")

LOBES = ["back", "hang", "wallR", "mid", "maw", "spill"]
SIDES = ["flesh_side", "flesh_side_dark", "dead_side", "throat", "throat_floor", "gum", "heart_side", "tooth_side", "sclera_side"]


def f(x):
    s = repr(float(x))
    return s + "F"


def rows(name, items, ind="\t"):
    out = ["%sstatic final float[][] %s = {" % (ind, name)]
    for it in items:
        out.append("%s\t{%s}," % (ind, ", ".join(f(v) for v in it)))
    out.append("%s};" % ind)
    return "\n".join(out)


def main():
    tmp = tempfile.mkdtemp(prefix="devil_export_")
    subprocess.check_call([sys.executable, os.path.join(HERE, "eternity_devil_concept.py"), "export", tmp])
    with open(os.path.join(tmp, "eternity_devil_layout.json")) as fh:
        d = json.load(fh)
    atlas = Image.open(os.path.join(tmp, "eternity_devil.png")).convert("RGBA")
    os.makedirs(os.path.dirname(TEXTURE), exist_ok=True)
    shutil.copyfile(os.path.join(tmp, "eternity_devil.png"), TEXTURE)

    layers = d["layers"]
    tiles = d["tiles"]
    maw = d["maw"]
    mx, my, mw, mh = maw["rect"]
    jaw_v = my + mh * 0.45

    def opaque(lobe, u, v):
        lx, ly = layers[lobe]
        if u < 0 or v < 0 or u >= d["size"][0] or v >= d["size"][1]:
            return False
        return atlas.getpixel((lx + u, ly + v))[3] > 40

    boxes = []
    for b in d["boxes"]:
        jaw = 1 if b["lobe"] == "maw" and b["v0"] >= jaw_v else 0
        boxes.append([LOBES.index(b["lobe"]), b["u0"], b["u1"], b["v0"], b["v1"], b["z_back"], b["z_front"], SIDES.index(b["side"]), jaw] + b["uv_top"] + b["uv_bottom"] + b["uv_left"] + b["uv_right"])

    eyes = []
    for e in d["eyes"]:
        rx, ry, rw, rh = e["rect"]
        row = [LOBES.index(e["lobe"]), rx, ry, rw, rh, e["surface_z"], e["rest_gaze"][0], e["rest_gaze"][1], e["iris_d"]]
        row += e["uv_sclera"] + e["uv_iris"] + e["uv_lid"]
        eyes.append(row)

    teeth = []
    for t in maw["teeth"]:
        teeth.append([1 if t["upper"] else 0, 1 if t["over_heart"] else 0] + t["rect"] + t["uv"])

    small = []
    for s in d["small_mouths"]:
        small.append([LOBES.index(s["lobe"])] + s["rect"] + [s["surface_z"], 1 if s["vertical"] else 0])

    def surface(u, v):
        """The depth of the flesh at a point, and the lobe that gives it."""
        best = 0.0
        who = "back"
        for b in d["boxes"]:
            if b["u0"] <= u < b["u1"] and b["v0"] <= v < b["v1"] and opaque(b["lobe"], u, v) and b["z_front"] >= best:
                best = b["z_front"]
                who = b["lobe"]
        return best, who

    sinews = []
    for s in d["sinews"]:
        pts = [(u, v) + surface(u, v) for u, v in s["path"]]
        row = [s["thickness"], LOBES.index(pts[0][3])]
        for u, v, z, _ in pts:
            row += [u, v, z]
        sinews.append(row)

    h = maw["heart"]
    hx, hy, hw, hh = h["rect"]
    out = []
    out.append("package io.github.kortev.chainsawman.client;")
    out.append("")
    out.append("/**")
    out.append(" * GENERATED by tools/eternity_devil_atlas.py from the concept's export: do not edit by hand.")
    out.append(" *")
    out.append(" * <p>Every number is in texels, 16 to the block. The front is {@link #W} x {@link #H} texels: {@code u} runs right across it (the")
    out.append(" * devil's right is toward the hotel's +z), {@code v} runs down from the top of the 7-block front, {@code z} runs out from the")
    out.append(" * devil's back plane toward the players. The atlas is {@link #AW} x {@link #AH}; each lobe has a front layer of {@link #W} x {@link #H}")
    out.append(" * at {@link #LAYER_X}/{@link #LAYER_Y}, and the sprites (side tiles, heart, eyes, teeth) are below.")
    out.append(" */")
    out.append("final class EternityDevilLayout {")
    out.append("\tprivate EternityDevilLayout() {")
    out.append("\t}")
    out.append("")
    out.append("\tstatic final int AW = %d;" % d["atlas"][0])
    out.append("\tstatic final int AH = %d;" % d["atlas"][1])
    out.append("\tstatic final int W = %d;" % d["size"][0])
    out.append("\tstatic final int H = %d;" % d["size"][1])
    out.append("\t/** The column of the front that is on the corridor's axis (the maw's middle). */")
    out.append("\tstatic final int MAW_U = %d;" % d["maw_u"])
    out.append("\tstatic final String[] LOBE = {%s};" % ", ".join('"%s"' % n for n in LOBES))
    out.append("\tstatic final int[] LAYER_X = {%s};" % ", ".join(str(layers[n][0]) for n in LOBES))
    out.append("\tstatic final int[] LAYER_Y = {%s};" % ", ".join(str(layers[n][1]) for n in LOBES))
    out.append("\tstatic final int MAW_LOBE = %d;" % LOBES.index("maw"))
    out.append("")
    out.append("\t/** The side tiles {x, y, w, h}, by the index {@link #BOXES} gives. */")
    out.append("\tstatic final int[][] TILE = {")
    for n in SIDES:
        out.append("\t\t{%s}, // %s" % (", ".join(str(v) for v in tiles[n]), n))
    out.append("\t};")
    out.append("\tstatic final int T_FLESH = 0;")
    out.append("\tstatic final int T_FLESH_DARK = 1;")
    out.append("\tstatic final int T_DEAD = 2;")
    out.append("\tstatic final int T_THROAT = 3;")
    out.append("\tstatic final int T_THROAT_FLOOR = 4;")
    out.append("\tstatic final int T_GUM = 5;")
    out.append("\tstatic final int T_HEART_SIDE = 6;")
    out.append("\tstatic final int T_TOOTH_SIDE = 7;")
    out.append("\tstatic final int T_SCLERA_SIDE = 8;")
    out.append("")
    out.append("\t/** The lobe boxes: {lobe, u0, u1, v0, v1, zBack, zFront, side tile, jaw (1: the lower lip, which drops), then the top, bottom, left and right edge strips {x, y, w, h} each}. */")
    out.append(rows("BOXES", boxes))
    out.append("")
    out.append("\t/** The eyes: {lobe, rx, ry, rw, rh, surfaceZ, restGazeX, restGazeY, irisD, sclera x y w h, iris x y w h, lid x y w h}. */")
    out.append(rows("EYES", eyes))
    out.append("")
    out.append("\t/** The great mouth: its opening {x, y, w, h}, the face it is cut in, and the cavity behind it. */")
    out.append("\tstatic final int[] MAW = {%d, %d, %d, %d};" % (mx, my, mw, mh))
    out.append("\tstatic final float MAW_Z = %s;" % f(maw["surface_z"]))
    out.append("\tstatic final float CAVITY = %s;" % f(maw["cavity_depth"]))
    out.append("\t/** The teeth: {upper, overHeart, rx, ry, rw, rh, sprite x y w h}. */")
    out.append(rows("TEETH", teeth))
    out.append("\t/** The heart's rectangle on the front, its front plane z, and its sprite. */")
    out.append("\tstatic final int[] HEART = {%d, %d, %d, %d};" % (hx, hy, hw, hh))
    out.append("\tstatic final float HEART_Z = %s;" % f(h["z"]))
    out.append("\tstatic final int[] HEART_UV = {%s};" % ", ".join(str(v) for v in h["uv"]))
    out.append("")
    out.append("\t/** The small mouths: {lobe, rx, ry, rw, rh, surfaceZ, vertical}. */")
    out.append(rows("SMALL_MOUTHS", small))
    out.append("")
    out.append("\t/** The sinews: {thickness, lobe, then u, v, z of each point of the path}. */")
    out.append(rows("SINEWS", sinews))
    out.append("}")
    with open(JAVA, "w", newline="\n") as fh:
        fh.write("\n".join(out) + "\n")
    print("wrote %s (%d boxes, %d eyes, %d teeth, %d small mouths, %d sinews) and %s" % (JAVA, len(boxes), len(eyes), len(teeth), len(small), len(sinews), TEXTURE))
    shutil.rmtree(tmp, ignore_errors=True)


if __name__ == "__main__":
    main()
